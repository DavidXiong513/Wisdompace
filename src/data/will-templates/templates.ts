// ── 遗嘱模板库 · 三份手抄范本 ──
//
// 全部按《民法典》继承编自书遗嘱要件编写：
// - 第 1134 条：自书遗嘱须由遗嘱人亲笔书写、签名，注明年、月、日
// - 第 1141 条：应当为缺乏劳动能力又没有生活来源的继承人保留必要遗产份额
// - 第 1142 条：数份遗嘱内容相抵触的，以最后的遗嘱为准
// - 第 1124 条：受遗赠人应当在知道受遗赠后六十日内表示接受，逾期视为放弃
//
// 重要：范本只供阅读参照，不能打印签署。自书遗嘱必须一字一句亲笔书写，
// 任何「填完打印、签个名」的做法在法律上是另一种文书（打印遗嘱），
// 需要两个以上见证人全程在场、遗嘱人和见证人每页签名并注明年月日。

export type TemplateVerdict = 'ok' | 'caution' | 'no';

export interface WillChecklist {
  /** 适用情形 */
  fit: string[];
  /** 不适用情形 */
  unfit: string[];
  /** 抄完必查 */
  mustCheck: string[];
}

export interface BodyLine {
  text: string;
  /** title 居中标题 / body 正文 / sign 签章行 */
  kind?: 'title' | 'body' | 'sign';
  /** 空行 */
  blank?: boolean;
}

export interface Annotation {
  /** 原文片段 */
  quote: string;
  /** 为什么必须写 */
  why: string;
  /** 不写会怎样 */
  risk: string;
}

export interface CostRow {
  label: string;
  value: string;
  level: 'low' | 'mid' | 'high';
}

export interface WillTemplate {
  slug: string;
  name: string;
  subtitle: string;
  verdict: TemplateVerdict;
  verdictLabel: string;
  checklist: WillChecklist;
  body: BodyLine[];
  annotations: Annotation[];
  costs: CostRow[];
  warnings: string[];
}

