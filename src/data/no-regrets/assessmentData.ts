// ── 年龄段与紧迫系数 ──

export function getUrgencyFactor(age: number): number {
  if (age <= 35) return 1.2;
  if (age <= 50) return 1.0;
  return 0.9;
}

export function getAgeStage(age: number): string {
  if (age <= 35) return "自我探索期";
  if (age <= 50) return "平衡调整期";
  return "意义整合期";
}

