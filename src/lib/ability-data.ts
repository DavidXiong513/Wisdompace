// === 数据转换 ===
function convertRaw(raw: (number | string | number[])[]): Ability {
  return {
    id: Number(raw[0]),
    name: String(raw[1]),
    def: String(raw[2]),
    domain: Number(raw[3]),
    batch: Number(raw[4]),
    prof: [String(raw[8]), String(raw[7]), String(raw[6]), String(raw[5])],   // 翻转为 [1级, 2级, 3级, 4级]
    inte: [String(raw[12]), String(raw[11]), String(raw[10]), String(raw[9])], // 翻转为 [1级, 2级, 3级, 4级]
    related: (raw[13] as number[]) || [],
  };
}

// 缓存转换结果
let _abilitiesCache: Ability[] | null = null;

export function getAllAbilities(): Ability[] {
  if (!_abilitiesCache) {
    _abilitiesCache = RAW_ABILITIES.map(convertRaw);
  }
  return _abilitiesCache;
}

export function getAbilityByIndex(idx: number): Ability | null {
  const all = getAllAbilities();
  return idx >= 0 && idx < all.length ? all[idx] : null;
}

export function getAbilityById(id: number): Ability | null {
  return getAllAbilities().find(a => a.id === id) || null;
}

export function getAbilitiesByBatch(batch: number): Ability[] {
  return getAllAbilities().filter(a => a.batch === batch);
}

export function getAbilitiesByDomain(domain: number): Ability[] {
  return getAllAbilities().filter(a => a.domain === domain);
}

// === 矛盾检测 ===
export function checkAlerts(
  ability: Ability,
  answers: Record<number, AbilityAnswer>
): AbilityAlert[] {
  const alerts: AbilityAlert[] = [];
  const myAns = answers[ability.id];
  if (!myAns?.p) return alerts;

  for (const rid of ability.related) {
    const rAns = answers[rid];
    if (!rAns?.p) continue;
    const diff = Math.abs(myAns.p - rAns.p);
    if (diff >= 3) {
      const ra = getAbilityById(rid);
      if (!ra) continue;
      alerts.push({
        abilityName: ability.name,
        abilityLevel: PROF_LABELS[myAns.p - 1],
        relatedName: ra.name,
        relatedLevel: PROF_LABELS[rAns.p - 1],
      });
    }
  }
  return alerts;
}

// === 四象限报告生成 ===
export function generateReport(
  answers: Record<number, AbilityAnswer>
): AbilityReport {
  const items = getAllAbilities();
  const answered = items.filter(a => answers[a.id]);

  const quadrants: Record<QuadrantKey, Ability[]> = {
    strength: [],
    potential: [],
    reserve: [],
    abandon: [],
  };

  const strengthDetail: QuadrantDetail = { hh: [], hm: [], mh: [], mm: [] };
  const potentialDetail: PotentialDetail = { l4: [], l3: [], n4: [], n3: [] };
  const reserveDetail: ReserveDetail = { h2: [], h1: [], m2: [], m1: [] };
  const abandonDetail: AbandonDetail = { ll: [], ln: [], nl: [], nn: [] };

  for (const a of answered) {
    const ans = answers[a.id];
    if (!ans) continue;
    const pHigh = ans.p >= 3;
    const iHigh = ans.i >= 3;

    if (pHigh && iHigh) {
      quadrants.strength.push(a);
      if (ans.p === 4 && ans.i === 4) strengthDetail.hh.push(a);
      else if (ans.p === 4 && ans.i === 3) strengthDetail.hm.push(a);
      else if (ans.p === 3 && ans.i === 4) strengthDetail.mh.push(a);
      else strengthDetail.mm.push(a);
    } else if (!pHigh && iHigh) {
      quadrants.potential.push(a);
      if (ans.p === 1 && ans.i === 4) potentialDetail.l4.push(a);
      else if (ans.p === 1 && ans.i === 3) potentialDetail.l3.push(a);
      else if (ans.p === 2 && ans.i === 4) potentialDetail.n4.push(a);
      else potentialDetail.n3.push(a);
    } else if (pHigh && !iHigh) {
      quadrants.reserve.push(a);
      if (ans.p === 4 && ans.i === 2) reserveDetail.h2.push(a);
      else if (ans.p === 4 && ans.i === 1) reserveDetail.h1.push(a);
      else if (ans.p === 3 && ans.i === 2) reserveDetail.m2.push(a);
      else reserveDetail.m1.push(a);
    } else {
      quadrants.abandon.push(a);
      if (ans.p === 1 && ans.i === 1) abandonDetail.ll.push(a);
      else if (ans.p === 1 && ans.i === 2) abandonDetail.ln.push(a);
      else if (ans.p === 2 && ans.i === 1) abandonDetail.nl.push(a);
      else abandonDetail.nn.push(a);
    }
  }

  // 6大能力域统计
  const domainStats = DOMAINS.map((domain, idx) => {
    const domainItems = getAbilitiesByDomain(idx);
    const avgP = domainItems.reduce((s, a) => s + (answers[a.id]?.p || 0), 0) / domainItems.length;
    const avgI = domainItems.reduce((s, a) => s + (answers[a.id]?.i || 0), 0) / domainItems.length;
    return { domain, avgProf: avgP, avgInte: avgI };
  });

  return {
    quadrants,
    strengthDetail,
    potentialDetail,
    reserveDetail,
    abandonDetail,
    domainStats,
  };
}

// === Markdown 导出 ===
export function exportMarkdown(
  answers: Record<number, AbilityAnswer>,
  name: string,
  years: string
): string {
  const items = getAllAbilities();
  let md = '# 42项能力兴趣自评报告\n\n';
  md += `- 姓名：${name || '未填写'}\n`;
  md += `- 工作年限：${years || '未填写'}\n`;
  md += `- 日期：${new Date().toLocaleDateString('zh-CN')}\n\n`;
  md += '| 能力 | 擅长度 | 喜欢度 |\n';
  md += '| --- | --- | --- |\n';
  for (const a of items) {
    const ans = answers[a.id];
    if (!ans) continue;
    md += `| ${a.name} | ${PROF_LABELS[ans.p - 1]} | ${['非常不喜欢','不太喜欢','比较喜欢','非常喜欢'][ans.i - 1]} |\n`;
  }
  return md;
}
